"""Preserve a post-preparation truncated local Q30 file, regenerate exact frozen bytes."""
import gzip, hashlib, json, shutil
import run_grid as g
rid='SRR29623266'
f=g.BASE/'inputs'/(rid+'.Q30.fastq.gz')
record=next(x for x in json.loads((g.BASE/'INPUT_MANIFEST.json').read_text()) if x['run']==rid)
failed=g.BASE/'failed_attempts/local_Q30_truncation';failed.mkdir(parents=True,exist_ok=False)
bad_hash=g.sha(f);shutil.move(f,failed/f.name)
stream=hashlib.sha256();N=K=0
with f.open('wb') as b,gzip.GzipFile(filename='',mode='wb',fileobj=b,mtime=0) as gz:
    for name,s,plus,q in g.rows(g.RAW/(rid+'.fastq.gz')):
        N+=1;stream.update((s+'\n'+q+'\n').encode())
        if sum(ord(x)-33 for x in q)>=30*len(q):
            K+=1;gz.write(('@'+name+'\n'+s+'\n+\n'+q+'\n').encode())
assert N==record['N_raw'] and K==record['Q30_pass'] and stream.hexdigest()==record['raw_sequence_quality_stream_sha256']
assert g.sha(f)==record['input_sha256'], 'Regenerated bytes must equal frozen prepared input.'
assert len(list(g.rows(f)))==K
for ref in ['mutant','programmed']:
    dest=failed/ref;dest.mkdir()
    ex=g.BASE/'executions'/ref/'baseline'/(rid+'.json')
    assert json.loads(ex.read_text())['state']=='FAILED'
    for p in ex.parent.glob(rid+'.*'):shutil.move(p,dest/p.name)
    folder=g.BASE/'runs'/ref/'baseline'/('CRISPResso_on_'+rid)
    shutil.move(folder,dest/folder.name)
shutil.copy2(g.BASE/'BASELINE_STATUS.json',failed/'BASELINE_STATUS.json')
g.dump(g.BASE/'INPUT_REPAIR.json',{'state':'EXACT_FROZEN_INPUT_RESTORED','created_utc':g.now(),'run':rid,'problem':'Local Q30 file truncated after manifest creation; cause not established. Both baseline attempts failed with gzip end-of-stream error.','preserved_bad_sha256':bad_hash,'restored_sha256':g.sha(f),'expected_sha256':record['input_sha256'],'raw_identity_verified':True,'Q30_pass':K})
print('EXACT_FROZEN_INPUT_RESTORED',flush=True)
